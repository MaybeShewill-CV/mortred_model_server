#!/usr/bin/env python3
"""Emit a GPU/gate evidence JSON with artifact digests + reproduce commands."""
from __future__ import annotations
import argparse, hashlib, json, datetime
from pathlib import Path
from zoneinfo import ZoneInfo

def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()

def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", required=True)
    ap.add_argument("--artifact", action="append", default=[],
                    help="name=...,path=... (repeatable)")
    ap.add_argument("--out", required=True)
    ap.add_argument("--root", default=".")
    args = ap.parse_args()
    root = Path(args.root).resolve()
    arts = []
    for spec in args.artifact:
        parts = dict(p.split("=", 1) for p in spec.split(",") if "=" in p)
        path = root / parts["path"]
        arts.append({
            "name": parts["name"],
            "path": parts["path"],
            "sha256": sha256_file(path) if path.is_file() else ("0" * 64),
            "media_type": "application/octet-stream",
        })
    doc = {
        "schema_version": "1",
        "product_version": args.version,
        "generated_at": datetime.datetime.now(ZoneInfo("Asia/Shanghai")).isoformat(),
        "artifacts": arts,
        "reproduce": [
            "python3 scripts/check_version_single_source.py --root .",
            f"python3 scripts/verify_gpu_gate_evidence.py --manifest {args.out}",
        ],
        "notes": "Generated by scripts/emit_gpu_gate_evidence.py",
    }
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(doc, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {out}")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
